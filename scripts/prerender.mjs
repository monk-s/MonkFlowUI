#!/usr/bin/env node
// Generates static HTML for every public route so crawlers and link
// previews (LinkedIn, Slack, X) see the right title, description, image
// and content without running JavaScript.
//
//   node scripts/prerender.mjs          write the files
//   node scripts/prerender.mjs --check  exit 1 if any file is out of date
//
// Input:  shell.html + marketing/{content,pages,site}.js
// Output: index.html, <route>/index.html, sitemap.xml, robots.txt
//
// Vercel serves a static file before it applies the catch-all rewrite in
// vercel.json, so /solutions/banks is answered by solutions/banks/index.html
// and everything else falls through to shell.html. In the browser, app.js
// re-renders the same markup, so there is nothing to hydrate.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

const ctx = vm.createContext({ URLSearchParams });
for (const f of ['content.js', 'pages.js', 'site.js']) {
  vm.runInContext(fs.readFileSync(path.join(root, 'marketing', f), 'utf8'), ctx, { filename: f });
}
const MK = ctx.MK;
const shell = fs.readFileSync(path.join(root, 'shell.html'), 'utf8');
const attr = (s) => MK.esc(s);

function replaceOnce(html, pattern, replacement, what) {
  if (!pattern.test(html)) throw new Error(`shell.html: could not find ${what}`);
  return html.replace(pattern, () => replacement);
}

function page(route) {
  const m = MK.metaFor(route);
  let html = shell;
  const meta = (key, name, value) =>
    (html = replaceOnce(html, new RegExp(`<meta ${key}="${name}" content="[^"]*" />`), `<meta ${key}="${name}" content="${attr(value)}" />`, `${key}=${name}`));

  html = replaceOnce(html, /<title>[^<]*<\/title>/, `<title>${attr(m.title)}</title>`, '<title>');
  meta('name', 'description', m.description);
  meta('name', 'robots', m.robots);
  html = replaceOnce(html, /<link rel="canonical" href="[^"]*" \/>/, `<link rel="canonical" href="${attr(m.canonical)}" />`, 'canonical');
  meta('property', 'og:type', m.ogType);
  meta('property', 'og:title', m.title);
  meta('property', 'og:description', m.description);
  meta('property', 'og:url', m.canonical);
  meta('property', 'og:image', m.ogImage);
  meta('name', 'twitter:title', m.title);
  meta('name', 'twitter:description', m.description);
  meta('name', 'twitter:image', m.ogImage);
  html = replaceOnce(html, /<script type="application\/ld\+json" id="mk-jsonld">[^<]*<\/script>/,
    `<script type="application/ld+json" id="mk-jsonld">${m.jsonLd.replace(/</g, '\\u003c')}</script>`, 'JSON-LD');

  html = replaceOnce(html, /<body>/, '<body class="mk-active">', '<body>');
  html = replaceOnce(html, /<div id="landing-container" class="hidden"><\/div>/,
    `<div id="landing-container" class="mk">${MK.shell(route.path, route.render())}</div>`, '#landing-container');
  return html.replace('<!DOCTYPE html>', `<!DOCTYPE html>\n<!-- GENERATED by scripts/prerender.mjs from shell.html + /marketing. Do not edit. -->`);
}

const outputs = new Map();
const routes = MK.routes.filter((r) => !r.noPrerender);
for (const route of routes) {
  const file = route.path === '/' ? 'index.html' : path.join(route.path.slice(1), 'index.html');
  outputs.set(file, page(route));
}
outputs.set('sitemap.xml',
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
  routes.map((r) => `  <url><loc>${MK.site.url}${r.path === '/' ? '/' : r.path}</loc></url>`).join('\n') + `\n</urlset>\n`);
outputs.set('robots.txt', `User-agent: *\nAllow: /\nDisallow: /api/\nDisallow: /shell.html\n\nSitemap: ${MK.site.url}/sitemap.xml\n`);

let stale = 0;
for (const [file, content] of outputs) {
  const full = path.join(root, file);
  const current = fs.existsSync(full) ? fs.readFileSync(full, 'utf8') : null;
  if (current === content) continue;
  stale++;
  if (check) { console.error(`out of date: ${file}`); continue; }
  fs.mkdirSync(path.dirname(full), { recursive: true });
  fs.writeFileSync(full, content);
  console.log(`wrote ${file}`);
}
if (check && stale) { console.error('Run: node scripts/prerender.mjs'); process.exit(1); }
console.log(check ? 'prerendered pages are up to date' : `${outputs.size} files checked, ${stale} written`);
